"""Export a trained model and its tuned decision settings to a C++ header.

    python train/export_cpp.py models/hush_tcn_v2.npz

Writes engine/src/model_weights.inc, which model_detector.cpp includes. The
weights are compiled into the library, so the engine needs no model file at
run time.
"""
import hashlib
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def arr(name, a):
    flat = np.asarray(a, dtype=np.float32).ravel()
    body = ",".join(f"{v:.9g}f" for v in flat)
    return f"static const float {name}[{flat.size}] = {{{body}}};\n"


def main():
    path = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT / "models" / "hush_tcn_v2.npz")
    d = np.load(path)
    dils = [int(v) for v in d["dils"]]
    k = int(d["k"])
    tuned = json.loads(path.with_suffix(".decision.json").read_text())
    digest = hashlib.sha256(path.read_bytes()).hexdigest()[:12]
    ch = [d[f"w{i}"].shape[0] for i in range(len(dils))]
    out = [
        f"// Generated by train/export_cpp.py from {path.name} (sha256 {digest}). Do not edit.\n",
        f'#define HUSH_MODEL_NAME "{path.stem}"\n',
        f"#define HUSH_MODEL_LAYERS {len(dils)}\n",
        f"#define HUSH_MODEL_K {k}\n",
        f"#define HUSH_MODEL_MELS {d['mean'].size}\n",
        f"static const int kModelDils[{len(dils)}] = {{{','.join(map(str, dils))}}};\n",
        f"static const int kModelChannels[{len(dils)}] = {{{','.join(map(str, ch))}}};\n",
        arr("kModelMean", d["mean"]),
        arr("kModelStd", d["std"]),
    ]
    for i in range(len(dils)):
        out.append(arr(f"kModelW{i}", d[f"w{i}"]))  # [out][in][k]
        out.append(arr(f"kModelB{i}", d[f"b{i}"]))
    out.append(arr("kModelWo", d["wo"]))
    out.append(arr("kModelBo", d["bo"]))
    out.append("static const float* const kModelW[] = {" + ",".join(f"kModelW{i}" for i in range(len(dils))) + "};\n")
    out.append("static const float* const kModelB[] = {" + ",".join(f"kModelB{i}" for i in range(len(dils))) + "};\n")
    out.append("// Decision settings tuned on validation calls (train/tune.py)\n")
    for key in ("on_th", "on_frames", "off_th", "off_frames", "lead_s", "tail_s", "min_hold_s", "merge_s"):
        out.append(f"#define HUSH_TUNED_{key.upper()} {tuned[key]}\n")
    dst = ROOT / "engine" / "src" / "model_weights.inc"
    dst.write_text("".join(out))
    n = sum(d[f"w{i}"].size + d[f"b{i}"].size for i in range(len(dils))) + d["wo"].size + d["bo"].size
    print(f"wrote {dst.relative_to(ROOT)}: {n} weights, layers {ch}, dilations {dils}")


if __name__ == "__main__":
    main()
